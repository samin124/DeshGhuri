export const userRelations = relations(user, ({ many }) => ({
  sessions: many(session),
  accounts: many(account),
  roles: many(userRole, { relationName: 'userRoles' }),
  createdRoles: many(userRole, { relationName: 'roleCreator' }),
}));
export const sessionRelations = relations(session, ({ one }) => ({
  user: one(user, {
    fields: [session.userId],
    references: [user.id],
  }),
}));
export const accountRelations = relations(account, ({ one }) => ({
  user: one(user, {
    fields: [account.userId],
    references: [user.id],
  }),
}));
export const userRole = pgTable(
  'user_role',
  {
    id: text('id').primaryKey(),
    userId: text('user_id')
      .notNull()
      .references(() => user.id, { onDelete: 'cascade' }),
    role: text('role').notNull(), // 'customer' | 'seller' | 'admin' | 'super_admin'
    createdAt: timestamp('created_at').defaultNow().notNull(),
    createdBy: text('created_by').references(() => user.id),
  },
  (table) => [
    index('userRole_userId_idx').on(table.userId),
    index('userRole_role_idx').on(table.role),
  ]
);
export const userRoleRelations = relations(userRole, ({ one }) => ({
  user: one(user, {
    fields: [userRole.userId],
    references: [user.id],
    relationName: 'userRoles',
  }),
  creator: one(user, {
    fields: [userRole.createdBy],
    references: [user.id],
    relationName: 'roleCreator',
  }),
}));
